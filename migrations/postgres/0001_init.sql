CREATE TABLE users (
    id            TEXT PRIMARY KEY,
    username      TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    enabled       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    BIGINT NOT NULL,
    updated_at    BIGINT NOT NULL
);
CREATE UNIQUE INDEX users_username_ascii_uq ON users ((lower(username COLLATE "C")));

CREATE TABLE sessions (
    id           TEXT PRIMARY KEY,
    user_id      TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash   BYTEA NOT NULL UNIQUE CHECK (octet_length(token_hash) = 32),
    created_at   BIGINT NOT NULL,
    last_seen_at BIGINT NOT NULL,
    expires_at   BIGINT NOT NULL,
    revoked_at   BIGINT,
    remote_ip    TEXT,
    user_agent   TEXT,
    CHECK (expires_at > created_at)
);
CREATE INDEX sessions_user_idx ON sessions(user_id);
CREATE INDEX sessions_expiry_idx ON sessions(expires_at);

CREATE TABLE devices (
    id            TEXT PRIMARY KEY,
    name          TEXT NOT NULL,
    metadata_json JSONB NOT NULL DEFAULT '{}'::jsonb
                  CHECK (jsonb_typeof(metadata_json) = 'object'),
    enabled       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    BIGINT NOT NULL,
    updated_at    BIGINT NOT NULL,
    last_seen_at  BIGINT
);
CREATE UNIQUE INDEX devices_name_ascii_uq ON devices ((lower(name COLLATE "C")));
CREATE INDEX devices_created_idx ON devices(created_at DESC, id DESC);
CREATE INDEX devices_enabled_idx ON devices(enabled);

CREATE TABLE device_credentials (
    id           TEXT PRIMARY KEY,
    device_id    TEXT NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    token_hash   BYTEA NOT NULL UNIQUE CHECK (octet_length(token_hash) = 32),
    status       TEXT NOT NULL CHECK (status IN ('active', 'revoked')),
    created_at   BIGINT NOT NULL,
    revoked_at   BIGINT,
    rotated_from TEXT REFERENCES device_credentials(id)
);
CREATE UNIQUE INDEX device_credentials_active_uq
    ON device_credentials(device_id) WHERE status = 'active';
CREATE INDEX device_credentials_device_idx ON device_credentials(device_id);

CREATE TABLE telemetry_id_allocator (
    id      SMALLINT PRIMARY KEY CHECK (id = 1),
    last_id BIGINT NOT NULL CHECK (last_id >= 0)
);
INSERT INTO telemetry_id_allocator (id, last_id) VALUES (1, 0);

CREATE TABLE telemetry_events (
    internal_id    BIGINT PRIMARY KEY CHECK (internal_id > 0),
    device_id      TEXT NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    event_id       TEXT NOT NULL CHECK (length(event_id) BETWEEN 1 AND 128),
    ts             BIGINT NOT NULL CHECK (ts > 0),
    received_at    BIGINT NOT NULL CHECK (received_at > 0),
    values_json    JSONB NOT NULL CHECK (jsonb_typeof(values_json) = 'object'),
    payload_sha256 BYTEA NOT NULL CHECK (octet_length(payload_sha256) = 32),
    UNIQUE (device_id, event_id)
);
CREATE INDEX telemetry_device_ts_idx ON telemetry_events(device_id, ts, internal_id);
CREATE INDEX telemetry_device_internal_idx ON telemetry_events(device_id, internal_id);
CREATE INDEX telemetry_received_idx ON telemetry_events(received_at, internal_id);

CREATE TABLE device_attributes (
    device_id  TEXT NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    key        TEXT NOT NULL CHECK (length(key) BETWEEN 1 AND 64),
    value_json JSONB NOT NULL CHECK (jsonb_typeof(value_json) IN ('boolean', 'number', 'string')),
    device_ts  BIGINT,
    updated_at BIGINT NOT NULL,
    PRIMARY KEY (device_id, key)
);

CREATE TABLE commands (
    id              TEXT PRIMARY KEY,
    device_id       TEXT NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    name            TEXT NOT NULL,
    params_json     JSONB NOT NULL CHECK (jsonb_typeof(params_json) = 'object'),
    status          TEXT NOT NULL
                    CHECK (status IN ('pending', 'dispatched', 'succeeded', 'failed', 'expired')),
    created_at      BIGINT NOT NULL,
    expires_at      BIGINT NOT NULL,
    next_attempt_at BIGINT NOT NULL,
    dispatched_at   BIGINT,
    completed_at    BIGINT,
    result_json     JSONB,
    error           TEXT,
    attempts        BIGINT NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    last_attempt_at BIGINT,
    idempotency_key TEXT,
    request_sha256  BYTEA CHECK (request_sha256 IS NULL OR octet_length(request_sha256) = 32),
    late_ack_at     BIGINT,
    late_ack_json   JSONB,
    CHECK (expires_at > created_at),
    CHECK ((idempotency_key IS NULL) = (request_sha256 IS NULL)),
    UNIQUE (device_id, idempotency_key)
);
CREATE INDEX commands_device_created_idx ON commands(device_id, created_at DESC, id DESC);
CREATE INDEX commands_due_idx ON commands(status, next_attempt_at, expires_at);
CREATE INDEX commands_status_expiry_idx ON commands(status, expires_at);

CREATE TABLE audit_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at  BIGINT NOT NULL,
    actor_type   TEXT NOT NULL CHECK (actor_type IN ('admin', 'device', 'system')),
    actor_id     TEXT,
    action       TEXT NOT NULL,
    target_type  TEXT,
    target_id    TEXT,
    request_id   TEXT,
    remote_ip    TEXT,
    details_json JSONB CHECK (details_json IS NULL OR jsonb_typeof(details_json) = 'object')
);
CREATE INDEX audit_occurred_idx ON audit_events(occurred_at DESC, id DESC);
CREATE INDEX audit_target_idx ON audit_events(target_type, target_id, occurred_at DESC);
